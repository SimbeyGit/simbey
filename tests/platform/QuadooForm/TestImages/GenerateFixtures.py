"""Deterministic image fixtures and a self-contained, no-script designer example.

Pillow is an asset-authoring dependency only. Production JPEG/BMP import uses
GDI+ and the bundled lodepng encoder; native tests verify that actual path.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import base64
import io
import json
import struct
import uuid

ROOT = Path(__file__).resolve().parent
TRUNK = ROOT.parents[3]
PROJECT = TRUNK / "platform" / "QuadooForm"


def png(image):
    stream = io.BytesIO()
    image.save(stream, format="PNG")
    return stream.getvalue()


def dib(image, legacy=False):
    width, height = image.size
    color = b"".join(bytes((b, g, r, 0 if legacy else a))
                     for y in range(height - 1, -1, -1) for x in range(width)
                     for r, g, b, a in [image.getpixel((x, y))])
    mask = b""
    for y in range(height - 1, -1, -1):
        row = bytearray(((width + 31) // 32) * 4)
        for x in range(width):
            if image.getpixel((x, y))[3] == 0:
                row[x // 8] |= 0x80 >> (x % 8)
        mask += row
    return struct.pack("<IiiHHIIiiII", 40, width, height * 2, 1, 32, 0,
                       len(color), 0, 0, 0, 0) + color + mask


def ico(entries):
    offset = 6 + 16 * len(entries)
    directory, payload = [], []
    for image, data in entries:
        width, height = image.size
        directory.append(struct.pack("<BBBBHHII", width % 256, height % 256,
                                     0, 0, 1, 32, len(data), offset))
        payload.append(data)
        offset += len(data)
    return struct.pack("<HHH", 0, 1, len(entries)) + b"".join(directory + payload)


rgba = Image.new("RGBA", (4, 2))
rgba.putdata([(255, 0, 0, 255), (0, 255, 0, 255), (0, 0, 255, 128), (255, 0, 255, 0),
              (255, 255, 0, 255), (0, 255, 255, 255), (255, 255, 255, 255), (0, 0, 0, 0)])
stripes = Image.new("RGBA", (6, 2))
stripes.putdata(([(255, 0, 0, 255)] * 2 + [(0, 255, 0, 255)] * 2 + [(0, 0, 255, 255)] * 2) * 2)
pattern = Image.new("RGBA", (17, 13))
pattern.putdata([((x * 37 + y * 11) % 256, (x * 7 + y * 53) % 256,
                  (x * 91 + y * 17) % 256, 255 if (x + y) % 3 else 0)
                 for y in range(13) for x in range(17)])
entries = []
for side, color in [(16, "red"), (32, "lime"), (48, "blue"), (256, "yellow")]:
    image = Image.new("RGBA", (side, side), color)
    entries.append((image, png(image) if side == 256 else dib(image)))
legacy = Image.new("RGBA", (2, 2))
legacy.putdata([(255, 0, 0, 255), (0, 0, 0, 0), (255, 255, 255, 0), (0, 255, 0, 255)])
plain = Image.new("RGB", (3, 2))
plain.putdata([(255, 0, 0), (0, 255, 0), (0, 0, 255),
               (255, 255, 0), (0, 255, 255), (255, 0, 255)])
jpeg, bmp = io.BytesIO(), io.BytesIO()
orientation = Image.Exif()
orientation[0x112] = 6
plain.save(jpeg, format="JPEG", quality=100, subsampling=0, exif=orientation)
plain.save(bmp, format="BMP")
fixtures = {"ImageRGBA": png(rgba), "ImageStripes": png(stripes),
            "ImagePattern": png(pattern), "ImageMultiICO": ico(entries),
            "ImageLegacyICO": ico([(legacy, dib(legacy, True))]),
            "ImageJPEG": jpeg.getvalue(), "ImageBMP": bmp.getvalue()}
lines = ["// Deterministic codec/rendering fixtures. Generated by TestImages/GenerateFixtures.py.", "#pragma once"]
for name, data in fixtures.items():
    lines.append("static const BYTE " + name + "[] = {")
    lines.extend("\t" + ",".join("0x%02x" % byte for byte in data[n:n + 24]) + ","
                 for n in range(0, len(data), 24))
    lines.append("};")
(ROOT / "ImageFixtures.h").write_bytes(("\n".join(lines) + "\n").replace("\n", "\r\n").encode())
for name, extension in [("ImageRGBA", "png"), ("ImageJPEG", "jpg"), ("ImageBMP", "bmp"), ("ImageMultiICO", "ico")]:
    (ROOT / (name + "." + extension)).write_bytes(fixtures[name])


def resource(data, format="png"):
    return {"format": format, "encoding": "base64", "data": base64.b64encode(data).decode("ascii")}


def control(kind, name, properties=None, children=None):
    result = {"schemaVersion": 1, "id": "{" + str(uuid.uuid5(uuid.NAMESPACE_OID, "QuadooForm.ImageExample." + name)).upper() + "}",
              "type": kind, "name": name, "properties": properties or {}}
    if children:
        result["children"] = children
    return result


def panel(name, x, y, width, height, color, child):
    return control("Panel", name, {"Left": x, "Top": y, "Width": width,
                                   "Height": height, "BackColor": color}, [child])


